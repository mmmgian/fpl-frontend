const ord = (n: number) => {
  const tens = n % 100;
  const one = n % 10;
  return `${n}${tens >= 11 && tens <= 13 ? "th" : one === 1 ? "st" : one === 2 ? "nd" : one === 3 ? "rd" : "th"}`;
};

